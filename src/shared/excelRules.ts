import type { ImportRowValidation } from './types';

export interface RawImportRow {
  rowNumber: number;
  studentCode: unknown;
  fullName: unknown;
  gender: unknown;
  classCode: unknown;
  pin: unknown;
  pinWasNumericCell?: boolean;
}

const FORMULA_PREFIX_RE = /^[=+\-@\t\r]/;

export function hasFormulaInjection(value: string): boolean {
  return FORMULA_PREFIX_RE.test(value.trimStart());
}

/**
 * Prevents spreadsheet formula execution when exporting CSV or Excel.
 */
export function sanitizeExportCell(value: unknown): string {
  const str = String(value ?? '');
  if (FORMULA_PREFIX_RE.test(str)) {
    return `'${str}`;
  }
  return str;
}

export function validateImportRows(
  rawRows: RawImportRow[],
  allowedClassCodes: string[],
  existingStudentsByClassAndCode: Map<string, { uid: string; fullName: string }>,
): {
  rows: ImportRowValidation[];
  validCount: number;
  errorCount: number;
  duplicateCount: number;
  createCount: number;
  updateCount: number;
} {
  const seenInFile = new Set<string>();
  const rows: ImportRowValidation[] = [];
  let validCount = 0;
  let errorCount = 0;
  let duplicateCount = 0;
  let createCount = 0;
  let updateCount = 0;

  const allowedUpper = new Set(allowedClassCodes.map((c) => c.trim().toUpperCase()));

  for (const raw of rawRows) {
    const errors: string[] = [];
    const sCodeRaw = String(raw.studentCode ?? '').trim();
    const fNameRaw = String(raw.fullName ?? '').trim();
    const genderRaw = String(raw.gender ?? '').trim();
    const cCodeRaw = String(raw.classCode ?? '').trim().toUpperCase();
    const pinRaw = raw.pin === undefined || raw.pin === null ? '' : String(raw.pin).trim();

    // Formula injection checks
    const fieldsToCheck: Array<[string, string]> = [
      ['Mã học sinh', sCodeRaw],
      ['Họ và tên', fNameRaw],
      ['Giới tính', genderRaw],
      ['Lớp', cCodeRaw],
      ['Mã PIN', pinRaw],
    ];
    for (const [colName, val] of fieldsToCheck) {
      if (val && hasFormulaInjection(val)) {
        errors.push(`Cột "${colName}" chứa kí tự công thức không hợp lệ (=, +, -, @).`);
      }
    }

    if (!sCodeRaw) {
      errors.push('Thiếu Mã học sinh.');
    } else if (!/^[a-zA-Z0-9_-]{2,24}$/.test(sCodeRaw)) {
      errors.push('Mã học sinh chỉ gồm chữ, số, gạch ngang/dưới (2–24 kí tự).');
    }

    if (!fNameRaw) {
      errors.push('Thiếu Họ và tên.');
    }

    if (!cCodeRaw) {
      errors.push('Thiếu Lớp.');
    } else if (!allowedUpper.has(cCodeRaw)) {
      errors.push(`Lớp "${cCodeRaw}" không thuộc phạm vi lớp được phân công của giáo viên.`);
    }

    const dedupKey = `${cCodeRaw}__${sCodeRaw.toUpperCase()}`;
    if (sCodeRaw && cCodeRaw) {
      if (seenInFile.has(dedupKey)) {
        duplicateCount++;
        errors.push(`Trùng Mã học sinh "${sCodeRaw}" trong cùng tệp tại lớp ${cCodeRaw}.`);
      } else {
        seenInFile.add(dedupKey);
      }
    }

    const isExisting = Boolean(sCodeRaw && cCodeRaw && existingStudentsByClassAndCode.has(dedupKey));

    let pinAutoGenerated = false;
    let pinMasked = '';
    if (raw.pinWasNumericCell) {
      errors.push(
        'Cột Mã PIN đang ở định dạng Số (Number) khiến Excel có thể làm mất số 0 đầu. Hãy định dạng cột Mã PIN là Text và nhập đủ 6 chữ số.',
      );
    } else if (pinRaw !== '') {
      if (!/^\d{6}$/.test(pinRaw)) {
        if (/^\d{1,5}$/.test(pinRaw)) {
          errors.push(
            `Mã PIN "${pinRaw}" chỉ có ${pinRaw.length} chữ số (có thể Excel đã làm mất số 0 ở đầu). Cần định dạng Text đủ 6 chữ số.`,
          );
        } else {
          errors.push('Mã PIN phải gồm đúng 6 chữ số (giữ số 0 ở đầu nếu có).');
        }
      } else {
        pinMasked = '••••••';
      }
    } else {
      if (!isExisting) {
        pinAutoGenerated = true;
        pinMasked = '(Tự sinh 6 số)';
      } else {
        pinMasked = '(Giữ PIN hiện tại)';
      }
    }

    const action: 'create' | 'update' | 'error' =
      errors.length > 0 ? 'error' : isExisting ? 'update' : 'create';

    if (action === 'error') {
      errorCount++;
    } else {
      validCount++;
      if (action === 'create') createCount++;
      else updateCount++;
    }

    rows.push({
      rowNumber: raw.rowNumber,
      studentCode: sCodeRaw,
      fullName: fNameRaw,
      gender: genderRaw,
      classCode: cCodeRaw,
      pinMasked,
      action,
      errors,
      pinAutoGenerated,
    });
  }

  return {
    rows,
    validCount,
    errorCount,
    duplicateCount,
    createCount,
    updateCount,
  };
}
