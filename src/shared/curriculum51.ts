export function isLessonVisibleToBranch(
  lesson: LessonCatalogItem,
  classGrade: number,
  branchSelection: BranchSelection,
): boolean {
  if (lesson.scope === 'common') return true;
  if (lesson.grade !== classGrade) return false;
  if (!lesson.branchGroup) return true;
  return lesson.branchGroup === branchSelection;
}

export function canPublishLesson(lesson: LessonCatalogItem): { allowed: boolean; reason?: string } {
  if (lesson.sourceStatus !== 'complete') {
    return {
      allowed: false,
      reason:
        lesson.sourceStatus === 'partial'
          ? 'Bài học mới có một phần trang SGK, cần bổ sung đủ trang trước khi xuất bản cho học sinh.'
          : 'Bài học mới có trong Mục lục SGK, cần đối chiếu nội dung đầy đủ trước khi xuất bản.',
    };
  }
  return { allowed: true };
}
