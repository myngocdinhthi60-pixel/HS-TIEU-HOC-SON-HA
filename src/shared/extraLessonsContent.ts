export interface ExtraLessonMeta {
  lessonId: string;
  badgeId: string;
  badgeName: string;
  watchTitle: string;
  watchDescription: string;
  watchExampleTip: string;
  guidedTitle: string;
  guidedInstruction: string;
  guidedExampleNote: string;
  guidedHint: string;
  practiceMissionTitle: string;
  practiceMissionSteps: string[];
  practiceExampleNote: string;
  practiceHint: string;
  practiceTasks?: PracticeTaskItem[];
  gameTitle: string;
  gameDescription: string;
  questions: QuizQuestion[];
}

function makeSimpleQuiz(
  lessonId: string,
  items: Array<{ q: string; opts: string[]; ans: number; exp: string }>,
): QuizQuestion[] {
  return items.map((item, idx) => ({
    id: `${lessonId}-Q${idx + 1}`,
    lessonId,
    type: 'single_choice',
    prompt: item.q,
    options: item.opts,
    correctAnswer: item.ans,
    explanation: item.exp,
  }));
}

